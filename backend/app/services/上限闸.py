"""上限闸：单窗主指标（点赞合计）触站规「热度上限」时的全局处置。

全局口径（两种可行架构只取其一，全站不混用）：

  选定「超额旁路」——触发上限的事件整笔不入窗、不改窗合计、不落撤回单，
  进旁路匣留证（原因=超热度上限）；窗合计保持上限之下的最后合法值。

  未选「截断入窗」——累计到上限截断、窗合计=上限、事件部分入窗、记截断审计。
  本系统不采用；截断口径下整笔旁路会致合计偏少，旁路口径下部分入窗会致
  窗表与事件合计撕裂，两口径混用即不可互证，故禁止。

可区分性（对「一笔过大点赞」的可观测签名）：
  本口径：窗合计不变（≤上限的最后合法值）且旁路匣有该事件留证；
  对侧口径：窗合计=上限、无旁路、有截断审计。读 /api/上限闸 即可分辨。

失败闭：闸口判定与窗/撤回/旁路写入在同一事务内（见 装载.装一批），
与迟到修正、关窗扫描交错时要么整体生效、要么整体回滚，不留半截；
判定本身只读窗表当前合计，不改库。落库即真相，不做只截展示的假截断。
"""
import json

主指标列 = "点赞合计"
增量列 = "点赞增量"
旁路原因 = "超热度上限"
策略名 = "超额旁路"


def 取上限(conn) -> int:
    """读站规热度上限。缺失/非法即失败闭：抛错→整批回滚，不放行任何事件。"""
    r = conn.execute("SELECT 值 FROM 站规 WHERE 键='热度上限'").fetchone()
    if not r:
        raise ValueError("站规缺「热度上限」，上限闸失败闭")
    try:
        上限 = int(str(r["值"]).strip())
    except (TypeError, ValueError):
        raise ValueError(f"站规「热度上限」不可解析:{r['值']}")
    if 上限 < 0:
        raise ValueError(f"站规「热度上限」为负:{上限}")
    return 上限


def 闸口判定(conn, 窗键: str, 点赞增量: int, 上限: int) -> dict:
    """只读判定：该增量若入窗，主指标是否越上限。越上限→整笔旁路，不得部分入窗。"""
    窗 = conn.execute(
        f"SELECT {主指标列} FROM 热度窗 WHERE 窗键=?", (窗键,)
    ).fetchone()
    旧合计 = int(窗[主指标列]) if 窗 else 0
    新合计 = 旧合计 + int(点赞增量)
    return {
        "放行": 新合计 <= 上限,
        "上限": 上限,
        "旧合计": 旧合计,
        "新合计": 新合计,
        "超出": max(0, 新合计 - 上限),
    }


def 记超上限旁路(conn, *, 事件编号, 房间键, 类型, 事件时, 处理时, 观众键,
                 点赞, 送礼, 批次编号, 窗键本应, 判, 迟到修正: bool) -> None:
    """整笔旁路落库（与判定同事务）：事件标已旁路不挂窗键 + 旁路匣留证。

    窗合计、版本、撤回单一概不动——这是与「截断入窗」的分界线。
    """
    conn.execute(
        """INSERT INTO 互动事件(事件编号,房间键,事件类型,事件时,处理时,观众键,点赞增量,送礼额,命运,窗键,批次编号)
           VALUES (?,?,?,?,?,?,?,?,?,?,?)""",
        (事件编号, 房间键, 类型, 事件时, 处理时, 观众键, 点赞, 送礼, "已旁路", "", 批次编号),
    )
    载荷 = {
        "事件编号": 事件编号,
        "窗键本应": 窗键本应,
        "策略": 策略名,
        "上限": 判["上限"],
        "窗合计": 判["旧合计"],
        "点赞增量": 点赞,
        "若入窗合计": 判["新合计"],
        "超出": 判["超出"],
        "迟到修正": bool(迟到修正),
        "事件时": 事件时,
        "处理时": 处理时,
    }
    conn.execute(
        "INSERT INTO 旁路匣(原因, 载荷, 时刻) VALUES (?,?,?)",
        (旁路原因, json.dumps(载荷, ensure_ascii=False), 处理时),
    )


def _证据(conn, 窗键: str) -> list:
    """该窗的超上限旁路留证（按旁路匣载荷中的窗键本应匹配）。"""
    out = []
    for r in conn.execute(
        "SELECT * FROM 旁路匣 WHERE 原因=? ORDER BY 编号", (旁路原因,)
    ):
        try:
            载荷 = json.loads(r["载荷"])
        except Exception:
            continue
        if 载荷.get("窗键本应") == 窗键:
            out.append({"编号": r["编号"], "时刻": r["时刻"], **载荷})
    return out


def 闸况(conn, 窗键: str, *, 上限: int = None, 窗行=None) -> dict:
    """上限闸只读接口：上限、窗合计、旁路证据、valid。窗不存在返回 None。"""
    if 上限 is None:
        上限 = 取上限(conn)
    窗 = 窗行 or conn.execute(
        "SELECT * FROM 热度窗 WHERE 窗键=?", (窗键,)
    ).fetchone()
    if not 窗:
        return None
    合计 = int(窗[主指标列])
    证据 = _证据(conn, 窗键)
    问题 = []
    if 合计 > 上限:
        问题.append(f"窗合计{合计}越上限{上限}")
    for e in 证据:
        ev = conn.execute(
            "SELECT 命运, 窗键 FROM 互动事件 WHERE 事件编号=?", (e.get("事件编号"),)
        ).fetchone()
        if not ev:
            问题.append(f"证据事件{e.get('事件编号')}未落库")
        elif ev["命运"] != "已旁路" or ev["窗键"] != "":
            问题.append(f"证据事件{e.get('事件编号')}命运{ev['命运']}不符已旁路")
    return {
        "窗键": 窗键,
        "房间键": 窗["房间键"],
        "状态": 窗["状态"],
        "策略": 策略名,
        "主指标": 主指标列,
        "上限": 上限,
        "窗合计": 合计,
        "余量": max(0, 上限 - 合计),
        "顶格": 合计 == 上限,
        "越限": 合计 > 上限,
        "证据": 证据,
        "valid": not 问题,
        "问题": 问题,
    }


def 全闸况(conn) -> dict:
    """全部热度窗的闸况汇总（只读）。"""
    上限 = 取上限(conn)
    窗列 = [
        闸况(conn, w["窗键"], 上限=上限, 窗行=w)
        for w in conn.execute("SELECT * FROM 热度窗 ORDER BY 窗起事件时 DESC")
    ]
    return {
        "策略": 策略名,
        "主指标": 主指标列,
        "上限": 上限,
        "窗数": len(窗列),
        "越限窗数": sum(1 for w in 窗列 if w["越限"]),
        "valid": all(w["valid"] for w in 窗列),
        "窗": 窗列,
    }
